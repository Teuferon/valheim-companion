// Generate the progress checklist exclusively from the shared game data.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => JSON.parse(readFileSync(path.join(root, file), 'utf8'));
const slug = name => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
export function buildProgressData() {
  const creatures = read('data/creatures.json');
  const items = [...read('data/materials.json'), ...read('data/items.json')];
  const creature = value => ({ id: value.id, name: value.name, names: value.names ?? {},
    image: value.stars?.[0]?.image ? '../bestiary/' + value.stars[0].image : null,
    portrait: 'img/bosses/' + value.id + '.webp',
    summon: value.summon, drops: value.drops ?? [] });
  const biomes = read('data/biomes.json').sort((a, b) => a.order - b.order).map(biome => {
    const bosses = creatures.filter(value => value.kind === 'boss' && biome.creatures.boss.includes(value.id));
    const minibosses = creatures.filter(value => value.kind === 'miniboss' && biome.creatures.miniboss.includes(value.id));
    const milestones = bosses.flatMap(boss => boss.drops.filter(drop => !/trophy/i.test(drop)).map(drop => {
      const name = drop.replace(/\s+x\d+$/i, '');
      const id = slug(name);
      const item = items.find(value => value.name.toLowerCase() === name.toLowerCase());
      const image = existsSync(path.join(root, 'apps/smithy/img/items', id + '.png')) ? '../smithy/img/items/' + id + '.png' : null;
      return { id, name, names: item?.names ?? {}, image, bossId: boss.id, drop };
    }));
    return { id: biome.id, name: biome.name, names: biome.names ?? {}, order: biome.order,
      art: 'img/biomes/' + biome.id + '.webp', thumb: 'img/biomes/' + biome.id + '-s.webp',
      bosses: bosses.map(creature), minibosses: minibosses.map(creature), milestones };
  });
  const output = path.join(root, 'apps/progress/data');
  mkdirSync(output, { recursive: true });
  writeFileSync(path.join(output, 'data.js'), '// Generated by scripts/build-progress-data.mjs — DO NOT EDIT MANUALLY.\nwindow.VP_DATA = ' + JSON.stringify({ biomes }, null, 2) + ';\n');
  const rows = biomes.flatMap(biome => biome.milestones.map(item => `| ${biome.name} | ${biome.bosses.find(boss => boss.id === item.bossId).name} | ${item.drop} | ${item.id} | ${item.image ?? '—'} |`));
  writeFileSync(path.join(root, 'data/report-progress.md'), '# Progress milestones\n\nGenerated from boss drops in `data/creatures.json`. Every non-trophy drop is included, including powers listed in the source data. No drops are inferred.\n\n| Biome | Boss | Drop | Milestone ID | Image |\n|---|---|---|---|---|\n' + rows.join('\n') + '\n');
  console.log(`Progress: ${biomes.length} biomes, ${biomes.reduce((n, b) => n + b.milestones.length, 0)} milestones.`);
  return { biomes };
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildProgressData();
